const dicts: Record<string, Dict> = { en, fr }
let lang = (() => {
  const l = (typeof navigator !== 'undefined' && navigator.language ? navigator.language : 'en').slice(0, 2)
  return l === 'fr' ? 'fr' : 'en'
})()
const listeners = new Set<() => void>()

export function setLang(l: string) {
  if (l === 'auto' || !l) l = (navigator.language || 'en').slice(0, 2)
  lang = dicts[l] ? l : 'en'
  document.documentElement.lang = lang
  listeners.forEach((fn) => fn())
}

export function getLang() {
  return lang
}

export function onLangChange(fn: () => void) {
  listeners.add(fn)
  return () => {
    listeners.delete(fn)
  }
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang]?.[key] ?? en[key] ?? key
  if (vars) {
    for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]))
  }
  return s
}

export const languages = [
  { id: 'auto', label: 'Auto' },
  { id: 'en', label: 'English' },
  { id: 'fr', label: 'Français' },
]

// Default custom commands keep their English name in the preferences;
// show a translated name until the user renames them.
const DEFAULT_COMMANDS: Record<string, string> = {
  tar: 'Archive (tar.gz)', untar: 'Extract tar archive', unzip: 'Extract zip archive', grep: 'Search text (grep)', du: 'Disk usage', exec: 'Execute',
}

const DEFAULT_SNIPPETS: Record<string, string> = {
  df: 'Disk space', free: 'Memory', biggest: 'Biggest files here', logs: 'Last system logs',
}

/** The name of a saved terminal command (the default ones are translated). */
export function snippetName(s: { id: string; name: string }): string {
  return DEFAULT_SNIPPETS[s.id] === s.name ? t(`snippet.${s.id}`) : s.name
}

export function commandName(c: { id: string; name: string }): string {
  return DEFAULT_COMMANDS[c.id] === c.name ? t(`cmd.${c.id}`) : c.name
}
